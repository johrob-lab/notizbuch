export type Pt = [number, number];
export type Glyph = { w: number; s: Pt[][] };

const rad = (d: number): number => (d * Math.PI) / 180;

/** Bogen einer Ellipse, Winkel in Grad gegen den Uhrzeigersinn (y nach oben). */
function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, step = 18): Pt[] {
  const n = Math.max(2, Math.ceil(Math.abs(a1 - a0) / step));
  return Array.from({ length: n + 1 }, (_, i) => {
    const a = rad(a0 + ((a1 - a0) * i) / n);
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)] as Pt;
  });
}
const oval = (cx: number, cy: number, rx: number, ry: number, start = 90): Pt[] => arc(cx, cy, rx, ry, start, start + 360);

/** Bogen für n, h, m: von (x0, 3.9) über die Kuppe nach unten bis (x1, 0). */
function arch(x0: number, x1: number, top = 6): Pt[] {
  const mid = (x0 + x1) / 2;
  const q = (x1 - x0) / 4;
  return [
    [x0, top - 2.1],
    [x0 + q * 0.5, top - 0.6],
    [mid - q * 0.4, top - 0.05],
    [mid + q * 0.7, top - 0.4],
    [x1 - q * 0.3, top - 1.8],
    [x1, top - 3.2],
    [x1, 0],
  ];
}

const dots = (xs: number[], y: number): Pt[][] => xs.map((x) => [[x, y], [x, y + 0.8]] as Pt[]);

